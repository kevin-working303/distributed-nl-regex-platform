import { useState } from "react";
import { api } from "../api/client";
import { useJobPolling } from "../hooks/useJobPolling";
import ResultsTable from "./ResultsTable";

export default function JobProgress({ jobId, onReset }) {
  const { job, error } = useJobPolling(jobId);
  const [cancelling, setCancelling] = useState(false);

  if (error) return <div className="card error">{error}</div>;
  if (!job) return <div className="card muted">Loading job…</div>;

  const running = job.status === "QUEUED" || job.status === "RUNNING";

  const cancel = async () => {
    setCancelling(true);
    try {
      await api.cancelJob(jobId);
    } finally {
      setCancelling(false);
    }
  };

  return (
    <div>
      <div className="card">
        <h2>4 · Job status</h2>
        <div className="statusline">
          <span className={`badge badge-${job.status.toLowerCase()}`}>{job.status}</span>
          <span className="muted">{job.stage}</span>
        </div>
        <div className="progress">
          <div className="progress-bar" style={{ width: `${job.progress}%` }} />
        </div>
        <div className="muted small">{job.progress}%</div>

        {job.spec && (
          <div className="spec">
            <div className="spec-title">Generated by LLM{job.spec.source === "cache" ? " (cached)" : job.spec.source === "heuristic" ? " (heuristic)" : ""}:</div>
            {job.spec.pattern && <code className="mono block">{job.spec.pattern}</code>}
            {job.spec.rules && (
              <ul className="rules">
                {job.spec.rules.map((r, i) => (
                  <li key={i}>
                    <code className="mono">{r.pattern}</code> → <code className="mono">{r.replacement}</code>
                  </li>
                ))}
              </ul>
            )}
            {job.spec.explanation && <div className="muted small">{job.spec.explanation}</div>}
          </div>
        )}

        {job.status === "SUCCESS" && (
          <div className="stats">
            <div><strong>{job.match_count?.toLocaleString()}</strong> matches</div>
            <div><strong>{job.row_count?.toLocaleString()}</strong> rows processed</div>
          </div>
        )}
        {job.status === "FAILED" && <div className="error">{job.error || "Job failed."}</div>}

        <div className="actions">
          {running && (
            <button className="danger" onClick={cancel} disabled={cancelling}>
              {cancelling ? "Cancelling…" : "Cancel"}
            </button>
          )}
          <button className="link" onClick={onReset}>Start a new job</button>
        </div>
      </div>

      {job.status === "SUCCESS" && <ResultsTable jobId={jobId} total={job.row_count} />}
    </div>
  );
}
